DATA SEGMENT
    DATA_LIST DW -1,0,2,5,4
    MAX DW ?
    MIN DW ?
    
DATA ENDS
CODE SEGMENT
    ASSUME CS:CODE, DS:DATA
START:
    MOV AX,DATA
    MOV DS,AX
    MOV CX,5
    DEC CX
LOOP1:
    MOV SI,CX
    MOV BX,0
LOOP2:
    MOV AX,DATA_LIST [BX]
    CMP AX,DATA_LIST [BX+2]
    JB LOOP3
    XCHG AX,DATA_LIST [BX+2];如果前面的值大则对换
    MOV DATA_LIST [BX],AX
LOOP3:
    ADD BX,2
    LOOP LOOP2;内层循环将大数存底
    MOV CX,SI
    LOOP LOOP1
OVER:
    MOV BX,OFFSET DATA_LIST
    MOV AX,[BX]
    MOV MIN,AX
    ADD BX,4
    MOV AX,[BX]
    MOV MAX,AX
    MOV AH,4CH
    INT 21H
CODE ENDS
    END START