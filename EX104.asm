DATAS SEGMENT
DZHANG EQU 280H ;点阵行接 280H
DZLIE EQU 288H ;点（绿）列行接 290H，若红接 288H
OUTPA EQU 298H ;8255A,B,C,端口
OUTPB EQU 299H
OUTPC EQU 29AH
SETUP EQU 29BH ;8255 控制端口
DATA01 DB 10 DUP(0) ;a0=AL 抢答数据
DATA02 DB 15 DUP(0) ;a0=0 空;a1~a8:八个抢答器状态 1:抢答,0:没抢答,a9 记录有几个，a10 记录哪一个抢答器 1
SHULIST DB 3FH,06H,5BH,4FH,66H,6DH,7DH,07H,7FH,6FH,77H,7CH,39H,5EH,79H,71H
ASCLL DB 30H,31H,32H,33H,34H,35H,36H,37H,38H,39H
DZHANG01 DB 41H,22H,14H,0FFH,00H,7EH,42H,7EH
DZLIE01 DB 01H,02H,04H,08H,10H,20H,40H,80H
DATAS ENDS
STACKS SEGMENT STACK
DB 200 DUP(0)
STACKS ENDS
CODES SEGMENT
ASSUME CS:CODES,DS:DATAS,SS:STACKS
START:
MOV AX,DATAS
MOV DS,AX
;---------------------
MOV AL,10001001B ;8255 初始化,A、B 方式 0 输出，C 输入
MOV DX,SETUP ;A: OUT, C: IN
OUT DX,AL
;------------------------
LOP01:
MOV DX,OUTPC
XOR AX,AX
IN AL,DX
CMP AL,0
JA NEXT01 ;AL 有值跳出循环
JMP LOP01

NEXT01:
MOV SI,OFFSET DATA01
MOV [SI],AL
MOV DI,OFFSET DATA02
MOV BX,8

LOP02:
MOV AL,[SI]
MOV CL,8
SUB CL,BL
CMP CL,1
JB NEXT02
SHR AL,CL

NEXT02:
AND AL,01H
MOV [DI+BX],AL ;采集数据到 DATA02
CMP AL,1
JB NEXT04
MOV [DI+10],BL

NEXT04:
ADD [DI+9],AL
DEC BX
CMP BX,0
JA LOP02

NEXT03:
MOV AL,10000000B
MOV DX,OUTPB
OUT DX,AL
MOV DI,OFFSET DATA02 ;a0=0 空;a1~a8:八个抢答器状态 1:抢答,0:没抢答,a9 记录有几个，a10 记录哪一个抢答器 1
MOV BL,[DI+10]
MOV BH,0
MOV SI,OFFSET SHULIST
MOV AL,[SI+BX]
MOV DX,OUTPA
OUT DX,AL ;数码管显示
;----------------------
LOP04:
MOV SI,OFFSET DZLIE01 ;点阵显示
MOV DI,OFFSET DZHANG01
MOV BX,0

LOP03:
MOV DX,DZLIE
MOV AL,[SI+BX]
OUT DX,AL
MOV DX,DZHANG
MOV AL,[DI+BX]
OUT DX,AL
CALL DELAY01
MOV AL,0
OUT DX,AL ;熄灭

INC BX
CMP BX,8 ;显示 0~7
JB LOP03
MOV DL,0FFH
MOV AH,06H
INT 21H
JZ LOP04 ;ZF=1,无键按下
CMP AL,' ' ;
JZ NEXT05 ;空格
JNZ NEXT06 ;不是空格
JMP LOP04 ;多余代码，防 bug

NEXT05: ;熄灭 ALL
MOV AL,0
MOV DX,OUTPB
OUT DX,AL
MOV DX,DZLIE
MOV AL,0
OUT DX,AL
MOV DX,OUTPA
OUT DX,AL
JMP LOP01

NEXT06:
;----------------------------
MOV AH,4CH
INT 21H
;------------------------延时
DELAY01 PROC
PUSH CX
MOV CX,1000
DELAY01LOP:
NOP
LOOP DELAY01LOP
POP CX
RET
DELAY01 ENDP
CODES ENDS
END START


