DATA SEGMENT
  DATA_LIST DB 50H,?,50H DUP(?)
DATA ENDS

CODE SEGMENT 
  ASSUME CS:CODE, DS:DATA
START:
  MOV AX,DATA
  MOV DS,AX
  MOV BX,OFFSET DATA_LIST
  MOV DX,BX
  MOV AH,0AH
  INT 21H  
  MOV CH,0
  MOV CL,[BX+1]
  ADD BX,2

LOOP1:
  MOV DX,[BX]
  MOV AH,02H
  INT 21H
  INC BX
  LOOP LOOP1
  MOV AH,4CH
  INT 21H 
CODE ENDS
    END START